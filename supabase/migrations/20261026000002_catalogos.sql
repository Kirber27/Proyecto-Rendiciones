-- Catálogos con la grafía exacta del Excel original (incluidos espacios finales).
-- Los datos se cargan en la migración de datos iniciales.

create table public.centros_costo (
  id smallint generated by default as identity primary key,
  codigo text not null unique,
  orden smallint not null default 0
);

create table public.cuentas (
  id smallint generated by default as identity primary key,
  nombre text not null unique,
  orden smallint not null default 0
);

create table public.subcuentas (
  id smallint generated by default as identity primary key,
  nombre text not null unique,
  cuenta_sugerida_id smallint references public.cuentas (id),
  orden smallint not null default 0,
  activa boolean not null default true
);

create table public.empresas (
  id smallint generated by default as identity primary key,
  nombre text not null unique,
  rut text,
  centro_costo_id smallint references public.centros_costo (id)
);

-- Bancos, cajas y "No Genera Pago" (lista "pag" del Excel).
create table public.medios_pago (
  id smallint generated by default as identity primary key,
  nombre text not null unique,
  orden smallint not null default 0
);

comment on table public.subcuentas is 'cuenta_sugerida_id: subcuenta_a_cuenta.json del prototipo.';
comment on table public.empresas is 'centro_costo_id: C.C. por defecto de las líneas de esa empresa.';
